-- MEDFLOW demo database
-- Run this file in Supabase SQL Editor.

create table if not exists public.emergency_requests (
  id bigint generated by default as identity primary key,
  resource text not null,
  quantity integer not null check (quantity > 0),
  department text not null,
  urgency text not null check (urgency in ('Critical', 'High', 'Normal')),
  status text not null default 'Open'
    check (status in ('Open', 'Matched')),
  created_at timestamptz not null default now()
);

create table if not exists public.alerts (
  id bigint generated by default as identity primary key,
  type text not null default 'warning',
  title text not null,
  message text not null,
  time text not null default 'Just now',
  unread boolean not null default true,
  created_at timestamptz not null default now()
);

insert into public.emergency_requests
  (resource, quantity, department, urgency, status)
select 'ICU Beds', 2, 'Emergency', 'Critical', 'Open'
where not exists (
  select 1 from public.emergency_requests
);

insert into public.emergency_requests
  (resource, quantity, department, urgency, status)
select 'O+ Blood', 4, 'Blood Bank', 'High', 'Open'
where (
  select count(*) from public.emergency_requests
) = 1;

