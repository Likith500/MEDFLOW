alter table public.emergency_requests enable row level security;
alter table public.alerts enable row level security;

grant select, insert, update on public.emergency_requests to anon;
grant select, insert, update on public.alerts to anon;

drop policy if exists "Demo users can read emergency requests"
  on public.emergency_requests;
create policy "Demo users can read emergency requests"
  on public.emergency_requests
  for select
  to anon
  using (true);

drop policy if exists "Demo users can create emergency requests"
  on public.emergency_requests;
create policy "Demo users can create emergency requests"
  on public.emergency_requests
  for insert
  to anon
  with check (true);

drop policy if exists "Demo users can update emergency requests"
  on public.emergency_requests;
create policy "Demo users can update emergency requests"
  on public.emergency_requests
